"""Data contracts for the indicators and the ontology, as files people and tools can read.

catalog/contracts/<key>.odcs.yaml   one per indicator, in the Open Data Contract Standard
                                    (ODCS v3.1.0): source, shape, coverage and freshness
catalog/ontology.yaml               the concepts, the indicators measuring each, and relations
catalog/ontology.md                 the same as a diagram (Mermaid, drawn by GitHub)

They are generated from indicators.py and ontology.py, which stay the single source of truth:

    uv run python -m macro_intelligence.contracts

A test fails when the files are out of date or not valid ODCS.
"""

from pathlib import Path

import yaml

from .indicators import CATALOG, SOURCE_NAMES, Indicator
from .ontology import CONCEPTS

ODCS_VERSION = "v3.1.0"
CATALOG_DIR = Path(__file__).resolve().parents[2] / "catalog"  # at the repository root
HEADER = "# Generated by `uv run python -m macro_intelligence.contracts`; don't edit by hand.\n"

SERVERS = {
    "bcb": ("bcb-sgs", "https://api.bcb.gov.br/dados/serie/bcdata.sgs.{code}/dados"),
    "worldbank": ("world-bank", "https://api.worldbank.org/v2/country/all/indicator/{code}"),
}


def _limitations(ind: Indicator) -> str:
    notes = ["Covers Brazil only." if ind.country == "BRA" else "Covers any country."]
    if ind.frequency == "daily":
        notes.append("The app keeps the last daily value of each month.")
    if ind.frequency == "annual":
        notes.append("A year's figures are published during the next year.")
    return " ".join(notes)


def contract(ind: Indicator) -> dict:
    """The ODCS data contract of one indicator."""
    concept = CONCEPTS[ind.concept]
    server, location = SERVERS[ind.source]
    is_annual = ind.frequency == "annual"
    custom = [
        {"property": "concept", "value": concept.key, "description": concept.name},
        {"property": "seriesCode", "value": ind.code},
        {"property": "coverage", "value": ind.country or "any country (ISO 3166-1 alpha-3)"},
    ]
    if ind.derived_from:
        custom.append({"property": "derivedFrom", "value": ind.derived_from})
    return {
        "apiVersion": ODCS_VERSION,
        "kind": "DataContract",
        "id": ind.key,
        "name": ind.name,
        "version": "1.0.0",
        "status": "active",
        "domain": "macroeconomics",
        "tags": [concept.key, "brazil" if ind.country == "BRA" else "world"],
        "description": {
            "purpose": ind.description,
            "usage": "Fetched on demand by macro-intelligence: pandas computes the statistics "
            "and an LLM explains them.",
            "limitations": _limitations(ind),
        },
        "servers": [
            {
                "server": server,
                "type": "api",
                "location": location.format(code=ind.code),
                "description": f"{SOURCE_NAMES[ind.source]}, series {ind.code}",
            }
        ],
        "schema": [
            {
                "name": "observations",
                "logicalType": "object",
                "description": "One value per country and date.",
                "properties": [
                    {
                        "name": "country",
                        "logicalType": "string",
                        "description": "ISO 3166-1 alpha-3 code.",
                        "required": True,
                        "primaryKey": True,
                        "primaryKeyPosition": 1,
                    },
                    {
                        "name": "date",
                        "logicalType": "string" if is_annual else "date",
                        "description": "Year (YYYY)." if is_annual else "Date (YYYY-MM-DD).",
                        "required": True,
                        "primaryKey": True,
                        "primaryKeyPosition": 2,
                    },
                    {
                        "name": "value",
                        "logicalType": "number",
                        "description": ind.units,
                        "required": True,
                        "quality": [
                            {"metric": "nullValues", "mustBe": 0, "dimension": "completeness"}
                        ],
                    },
                ],
            }
        ],
        "slaProperties": [
            {"property": "frequency", "value": ind.frequency},
            {
                "property": "latency",
                "value": ind.publication_lag_days,
                "unit": "d",
                "description": "About how long after its period a value is published.",
            },
        ],
        "customProperties": custom,
    }


def ontology() -> dict:
    """The concepts, the indicators measuring each, and the relations between indicators."""
    return {
        "concepts": [
            {
                "key": c.key,
                "name": c.name,
                "definition": c.definition,
                "measured_by": [i.key for i in CATALOG.values() if i.concept == c.key],
            }
            for c in CONCEPTS.values()
        ],
        "relations": [
            {"subject": i.key, "predicate": "derived_from", "object": i.derived_from}
            for i in CATALOG.values()
            if i.derived_from
        ],
    }


def ontology_mermaid() -> str:
    """The ontology as a Mermaid diagram: concepts, the indicators measuring them, their
    sources, and which indicator is derived from which."""
    lines = ["flowchart LR"]
    for c in CONCEPTS.values():
        lines.append(f'    concept_{c.key}(["{c.name}"])')
    for source, name in SOURCE_NAMES.items():
        lines.append(f'    source_{source}[("{name}")]')
    for i in CATALOG.values():
        lines.append(f'    {i.key}["{i.name}<br/>{i.frequency}"]')
    for i in CATALOG.values():
        lines.append(f"    {i.key} -->|measures| concept_{i.concept}")
        lines.append(f"    {i.key} -.->|published by| source_{i.source}")
        if i.derived_from:
            lines.append(f"    {i.key} -->|derived from| {i.derived_from}")
    return "\n".join(lines)


def ontology_markdown() -> str:
    """The ontology for people: the diagram and the concepts' definitions."""
    definitions = "\n".join(f"| {c.name} | {c.definition} |" for c in CONCEPTS.values())
    return (
        "<!-- Generated by `uv run python -m macro_intelligence.contracts`; don't edit by hand. -->\n"
        "# Ontology\n\n"
        "Each indicator measures a concept and is published by a source; some are derived from "
        "another indicator. Indicators of the same concept are related but not always "
        "comparable (e.g. monthly vs. annual inflation).\n\n"
        f"```mermaid\n{ontology_mermaid()}\n```\n\n"
        "| Concept | Definition |\n| --- | --- |\n"
        f"{definitions}\n"
    )


def _yaml(data: dict) -> str:
    return HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)


def rendered() -> dict[str, str]:
    """Every catalog file, by path relative to CATALOG_DIR."""
    files = {"ontology.yaml": _yaml(ontology()), "ontology.md": ontology_markdown()}
    for ind in CATALOG.values():
        files[f"contracts/{ind.key}.odcs.yaml"] = _yaml(contract(ind))
    return files


def write_catalog(directory: Path = CATALOG_DIR) -> list[Path]:
    """Write the catalog files, removing contracts of indicators no longer in the catalog."""
    files = rendered()
    for stale in (directory / "contracts").glob("*.odcs.yaml"):
        if f"contracts/{stale.name}" not in files:
            stale.unlink()
    written = []
    for relative, text in files.items():
        path = directory / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


if __name__ == "__main__":
    for path in write_catalog():
        print(path.relative_to(CATALOG_DIR.parent))
